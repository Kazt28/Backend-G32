# Sirve para comparar varios operadores de comparacion

tiene_dinero = True
tiene_tiempo = True
tiene_energia = False

# and > Todas las condiciones tienen que ser VERDADERAS, Si alguna es False todo es Falso

print(tiene_dinero and tiene_tiempo and tiene_energia)

# or > Basta con que una condicion sea VERDADERA para que todo sea TRUE

print(tiene_dinero or tiene_energia or tiene_tiempo)


